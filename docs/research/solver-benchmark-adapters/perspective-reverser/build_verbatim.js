// Builds tool_verbatim.js from PerspectiveReverser's js/main.js (gaider10, commit 7cba395) by copying
// fixed line ranges unchanged. Only glue (the wrapper function, stubs for alert/requestRedraw, the
// image-size setup that setFrameImage does when a screenshot is loaded) is added around them.
// Usage: node build_verbatim.js PATH/TO/main.js
const fs = require("fs");
const path = require("path");

const src = fs.readFileSync(process.argv[2], "utf8").split(/\r?\n/);
const take = (a, b) => `// ---- main.js lines ${a}-${b} (verbatim) ----\n` + src.slice(a - 1, b).join("\n") + "\n";

const RANGES = {
    core: [14, 282],            // project, projectedError, gradientDescent, perParamDescent, randomDescent, reverseProjection
    defaultState: [405, 469],   // const defaultState = {...}
    stateInit: [476, 476],      // let state = JSON.parse(JSON.stringify(defaultState));
    imageVars: [500, 501],      // let imageWidth = null; let imageHeight = null;
    createPoint: [1252, 1262],  // function createPoint(...)
    setImageSize: [1198, 1202], // screen size defaults when an image is loaded (inside setFrameImage)
    reverseBody: [2831, 2896],  // body of the "Reverse" button click handler
    projectFns: [3399, 3463],   // projectConstants, projectVariables, projectVariablesLocked, projectFrames
};

// sanity checks so a moved range fails loudly instead of silently copying the wrong code
const expect = {
    14: "function project(", 280: "function reverseProjection(", 405: "const defaultState = {",
    476: "let state = JSON.parse(JSON.stringify(defaultState));", 500: "let imageWidth = null;",
    1252: "function createPoint(", 1198: "if (imageWidth !== null", 2831: "if (imageWidth === null) return;",
    3399: "function projectConstants()", 3461: "function projectFrames()",
};
for (const [line, text] of Object.entries(expect)) {
    if (!src[line - 1].includes(text)) throw new Error(`main.js line ${line} is not '${text}': ${src[line - 1]}`);
}

let out = `// GENERATED by build_verbatim.js from PerspectiveReverser main.js (commit 7cba395). Do not edit.
// Ranges copied verbatim: ${JSON.stringify(RANGES)}
"use strict";
${take(...RANGES.core)}
function createTool(newImageWidth, newImageHeight) {
    const alerts = [];
    function alert(message) { alerts.push(message); }   // glue: the page's alert() refusals are recorded
    function requestRedraw() {}                         // glue: no canvas
${take(...RANGES.defaultState)}
${take(...RANGES.stateInit)}
${take(...RANGES.imageVars)}
${take(...RANGES.createPoint)}
${take(...RANGES.projectFns)}
    // glue: addFrame() pushes this frame object and makes it the main frame (main.js 727-738)
    state.frames.push({ name: "", time: 0, timeLocked: true, points: [], lines: [] });
    state.mainFrameIndex = 0;
    // glue: setFrameImage() with a newImageWidth x newImageHeight screenshot (main.js 1185-1202)
    const prevImageWidth = imageWidth;
    const prevImageHeight = imageHeight;
    imageWidth = newImageWidth;
    imageHeight = newImageHeight;
${take(...RANGES.setImageSize)}
    }   // glue: closes the outer if of 1198 (its canvas-view lines 1203-1207 are display only)
    function pressReverse() {
${take(...RANGES.reverseBody)}
    }
    return {
        get state() { return state; },
        alerts, createPoint, pressReverse, projectConstants, projectVariables, projectFrames,
    };
}

module.exports = { project, projectedError, gradientDescent, perParamDescent, randomDescent, reverseProjection, createTool };
`;
fs.writeFileSync(path.join(__dirname, "tool_verbatim.js"), out);
console.log("wrote tool_verbatim.js");
